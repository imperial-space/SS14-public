using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Imperial.SyndieBattle.UI;

[GenerateTypedNameReferences]
public sealed partial class SyndieBattleRespawnControl : PanelContainer
{
    private int? _displayedSeconds;

    public event Action? OnRespawn;

    public SyndieBattleRespawnControl()
    {
        RobustXamlLoader.Load(this);
        RespawnButton.OnPressed += _ => OnRespawn?.Invoke();
    }

    public void UpdateCooldown(TimeSpan remaining)
    {
        var ready = remaining <= TimeSpan.Zero;
        var seconds = ready ? 0 : (int) Math.Ceiling(remaining.TotalSeconds);
        if (_displayedSeconds == seconds)
            return;

        _displayedSeconds = seconds;
        RespawnButton.Disabled = !ready;
        StatusLabel.Text = Loc.GetString(ready ? "syndiebattle-respawn-ready" : "syndiebattle-respawn-cooldown");
        CooldownLabel.Visible = !ready;
        CooldownLabel.Text = ready ? string.Empty : Loc.GetString("syndiebattle-respawn-cooldown-seconds", ("seconds", seconds));
    }
}
