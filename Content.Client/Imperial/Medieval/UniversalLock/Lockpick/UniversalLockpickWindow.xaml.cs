using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls;
using Robust.Client.Graphics;

namespace Imperial.Medieval.UniversalLock.Lockpick;

[GenerateTypedNameReferences]
public sealed partial class UniversalLockpickWindow : DefaultWindow
{
    public Action<int[]>? OnSetCode;
    private List<LineEdit> _inputs = new();
    private List<Slider> _sliders = new();
    private int _maxValue;
    private int[] _oldCode = new int[4];

    private bool _isLockpicking = false;

    public UniversalLockpickWindow()
    {
        RobustXamlLoader.Load(this);

        SetCodeButton.OnPressed += _ => SubmitCode();
        SetCodeButton.Text = Loc.GetString("UniversalLockpick-ui-setup-setcodebutton");
    }

    public void UpdateState(int maxValue, int length, int[] codeState)
    {
        _isLockpicking = false;
        SetCodeButton.Disabled = false;

        InfoLabel.Text = $"{Loc.GetString("UniversalLockpick-ui-setup-allowed-value-from")} 0 - {maxValue}";
        _maxValue = maxValue;

        InputsContainer.DisposeAllChildren();
        _inputs.Clear();
        _sliders.Clear();

        if (_oldCode is null || _oldCode.Length != length)
            _oldCode = new int[length];

        for (int i = 0; i < length; i++)
        {
            bool isGuessed = codeState[i] == 255;
            bool disableControl = isGuessed || _isLockpicking;

            Color color = Color.Transparent;
            string arrowText = "";

            switch (codeState[i])
            {
                case 255:
                    color = Color.Green;
                    arrowText = "✓";
                    break;
                case 1:
                    color = Color.FromHex("#d37e00a4");
                    arrowText = "▲";
                    break;
                case -1:
                    color = Color.FromHex("#d37e00a4");
                    arrowText = "▼";
                    break;
                case 2:
                    color = Color.FromHex("#003cd570");
                    arrowText = "▲▲";
                    break;
                case -2:
                    color = Color.FromHex("#003cd570");
                    arrowText = "▼▼";
                    break;
                case 0:
                default:
                    color = Color.FromHex("#ffffff00");
                    arrowText = "";
                    break;
            }

            var backgroundStyle = new StyleBoxFlat
            {
                BackgroundColor = color,
            };

            var rowContainer = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 10
            };

            var slider = new Slider
            {
                MinValue = 0,
                MaxValue = maxValue,
                Rounded = true,
                HorizontalExpand = true,
                Value = _oldCode[i],
                Disabled = disableControl
            };

            var input = new LineEdit
            {
                MinWidth = 45,
                MaxWidth = 45,
                Text = _oldCode[i].ToString(),
                Editable = !disableControl,
                StyleBoxOverride = backgroundStyle
            };

            var arrowLabel = new Label
            {
                MinWidth = 25, // Увеличено под двойные стрелки "↑↑"
                MaxWidth = 25,
                Text = arrowText,
                Align = Label.AlignMode.Center,
                FontColorOverride = color != Color.Transparent ? Color.White : Color.Gray
            };

            slider.OnValueChanged += val =>
            {
                input.Text = ((int)val.Value).ToString();
            };

            input.OnTextChanged += args =>
            {
                if (int.TryParse(args.Text, out var val))
                {
                    if (val < 0) val = 0;
                    if (val > _maxValue) val = _maxValue;

                    slider.Value = val;
                }
            };

            _sliders.Add(slider);
            _inputs.Add(input);

            rowContainer.AddChild(slider);
            rowContainer.AddChild(input);
            rowContainer.AddChild(arrowLabel);

            InputsContainer.AddChild(rowContainer);
        }
    }

    private void SubmitCode()
    {
        if (_isLockpicking)
            return;

        var code = new int[_inputs.Count];

        for (int i = 0; i < _inputs.Count; i++)
        {
            if (int.TryParse(_inputs[i].Text, out var val))
            {
                if (val < 0 || val > _maxValue)
                {
                    return;
                }
                code[i] = val;
            }
            else
            {
                code[i] = 0;
            }
        }

        _isLockpicking = true;
        SetCodeButton.Disabled = true;

        foreach (var slider in _sliders)
        {
            slider.Disabled = true;
        }
        foreach (var input in _inputs)
        {
            input.Editable = false;
        }

        _oldCode = code;
        OnSetCode?.Invoke(code);
    }
}
